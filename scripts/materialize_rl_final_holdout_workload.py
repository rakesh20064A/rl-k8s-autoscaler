#!/usr/bin/env python3
"""scripts/materialize_rl_final_holdout_workload.py

Phase 16V, task sec.7: "If Phase16U specifies it algorithmically but has not
materialized the actual schedule artifact yet, materialize it
deterministically now -- without running it, hash-pin it, and confirm it
has not appeared in any historical training/development execution."

This script performs EXACTLY that mechanical step, nothing more:
  1. Reads the frozen generation specification from
     task_outputs/phase_16u_training_and_evaluation_workload_split.json
     (`final_evaluation_workload` block) -- does not alter it.
  2. Writes the corresponding traffic-profile YAML, in the SAME schema
     already used by configs/traffic_profiles/mixed.yaml and
     configs/traffic_profiles/unseen_eval.yaml (a `phases` list), to
     configs/traffic_profiles/iteration_rl_final_holdout_v1.yaml.
  3. Computes and records its SHA-256 hash.
  4. Confirms this exact file did not exist before this run, and that its
     (seed, peak_rps, duration_seconds) tuple does not match any existing
     training/development profile or unseen_eval.yaml -- i.e. it has never
     been used in any historical execution, because it did not exist until
     this script ran.

CLASSIFICATION: OFFLINE_STATIC_MATERIALIZATION_ONLY. This script never
generates traffic, never opens a port-forward, never touches Kubernetes,
and never reads/executes the resulting YAML through the traffic runner.
Materializing a YAML file is not "opening" the held-out workload in the
sense docs/rl_mdp_spec.md sec.22 and phase_16u_direct_ppo_protocol.yaml
mean by that phrase -- inspection/execution of its generated TRAFFIC TRACE
is what remains forbidden until PPO training and this protocol are frozen
and unchanged, which is unaffected by this script existing on disk.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path
from typing import Any, Dict

PROJECT_ROOT = Path(__file__).resolve().parent.parent
WORKLOAD_SPLIT_PATH = PROJECT_ROOT / "task_outputs" / "phase_16u_training_and_evaluation_workload_split.json"
TRAFFIC_PROFILES_DIR = PROJECT_ROOT / "configs" / "traffic_profiles"
EXISTING_TRAINING_PROFILES = ("constant", "step", "burst", "ramp", "periodic", "mixed")
UNSEEN_EVAL_PATH = TRAFFIC_PROFILES_DIR / "unseen_eval.yaml"


def _load_spec() -> Dict[str, Any]:
    with open(WORKLOAD_SPLIT_PATH, "r", encoding="utf-8") as f:
        split = json.load(f)
    return split["final_evaluation_workload"]


def _render_yaml(spec: Dict[str, Any]) -> str:
    lines = [
        "# configs/traffic_profiles/iteration_rl_final_holdout_v1.yaml",
        "# MACHINE-GENERATED by scripts/materialize_rl_final_holdout_workload.py",
        "# from the frozen generation specification in",
        "# task_outputs/phase_16u_training_and_evaluation_workload_split.json",
        "# (final_evaluation_workload block). DO NOT hand-edit -- any change",
        "# must go through that frozen specification and a new materialization.",
        "#",
        "# FORMAL FINAL HELD-OUT EVALUATION WORKLOAD for the direct-PPO-vs-HPA",
        "# comparison (Phase16U/16V). Per phase_16u_training_and_evaluation_",
        "# workload_split.json: 'no phase, including the implementation phase,",
        "# may inspect this workload's generated traffic trace or run it",
        "# against any controller before both PPO training and the entire",
        "# Phase16U protocol are frozen and unchanged.'",
        "",
        "profile: iteration_rl_final_holdout_v1",
        'description: "Formal final held-out PPO-vs-HPA evaluation workload -- materialized, never executed until authorized"',
        f"seed: {spec['seed']}",
        "",
        f"duration_seconds: {spec['duration_seconds']}",
        f"intensity: {spec['intensity']}",
        f"endpoint: {spec['endpoint']}",
        "",
        "phases:",
    ]
    for phase in spec["shape_specification"]["phases"]:
        lines.append(f"  - type: {phase['type']}")
        for key, value in phase.items():
            if key in ("type", "note"):
                continue
            lines.append(f"    {key}: {value}")
        if "note" in phase:
            lines.append(f"    # {phase['note']}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    spec = _load_spec()
    reserved_name = Path(spec["new_file_name_reserved"]).name
    target_path = TRAFFIC_PROFILES_DIR / reserved_name

    already_existed = target_path.exists()

    rendered = _render_yaml(spec)
    target_path.write_text(rendered, encoding="utf-8")

    sha256 = hashlib.sha256(rendered.encode("utf-8")).hexdigest()

    # Confirm no reuse of a previously-inspected magnitude/seed -- mechanical
    # cross-check, not a design decision (the design decision was already
    # made and frozen in Phase16U).
    conflicts = []
    if spec["seed"] in (42, 99):
        conflicts.append(f"seed {spec['seed']} collides with an existing training/unseen_eval seed")
    peak = spec["shape_specification"]["peak_rps"]
    known_training_peaks = {70, 60, 50, 45, 20, 5}
    if peak in known_training_peaks or peak == 80:  # 80 = unseen_eval.yaml's peak
        conflicts.append(f"peak_rps {peak} collides with a previously-inspected magnitude")

    result = {
        "script": "scripts/materialize_rl_final_holdout_workload.py",
        "classification": "OFFLINE_STATIC_MATERIALIZATION_ONLY",
        "source_specification": str(WORKLOAD_SPLIT_PATH.relative_to(PROJECT_ROOT)),
        "materialized_file": str(target_path.relative_to(PROJECT_ROOT)),
        "file_already_existed_before_this_run": already_existed,
        "sha256": sha256,
        "seed": spec["seed"],
        "duration_seconds": spec["duration_seconds"],
        "peak_rps": peak,
        "novelty_conflicts": conflicts,
        "novel_relative_to_training_and_unseen_eval": len(conflicts) == 0,
        "traffic_generated": False,
        "executed": False,
    }
    print(json.dumps(result, indent=2))
    return 0 if not conflicts else 1


if __name__ == "__main__":
    sys.exit(main())

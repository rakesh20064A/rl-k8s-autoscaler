"""tests/unit/test_iteration2b_r7_remediation_tooling.py

Phase 16J.1: backward-compatibility, isolation, and fail-closed tests for the
Iteration-2B r7-remediation execution tooling extension. These tests prove
that:

  1. The historical `scripts/run_dynamics_calibration_slot.py` CLI/behavior
     and the completed Iteration-2 24-slot campaign resolution are both
     byte-for-byte unchanged by this phase's additions.
  2. The new Iteration-2B remediation context (sequence, schedule registry,
     persistent root, ledger) is structurally isolated from BOTH the
     historical AND the completed Iteration-2 context and can never resolve
     to either.
  3. The Iteration-2B runner fails closed (raises, never proceeds) on any
     hash mismatch or out-of-range index.
  4. Neither the historical, Iteration-2, nor Iteration-2B CLI exposes an
     operator-facing override of any scientific parameter.
  5. A dry-run never mutates the Iteration-2B remediation ledger.

No traffic is generated by any test in this file; all live discovery calls
made by `--dry-run` are monkeypatched out exactly as the existing historical
and Iteration-2 dry-run tests already do.
"""
import json

import pytest

import scripts.dynamics_calibration_lib as lib
import scripts.run_dynamics_calibration_slot as harness
import scripts.run_iteration2_dynamics_calibration_slot as i2
import scripts.run_iteration2b_r7_remediation_slot as i2b


def _patch_transport_discovery(monkeypatch):
    monkeypatch.setattr(harness, "resolve_minikube_docker_network", lambda: "minikube")
    monkeypatch.setattr(harness, "resolve_minikube_node_ip", lambda: "192.168.49.2")
    monkeypatch.setattr(harness, "resolve_loadtest_nodeport", lambda: 31891)
    monkeypatch.setattr(
        harness, "resolve_relay_image_identity",
        lambda: {"image": "alpine/socat", "image_id": None, "repo_digest": None},
    )


class TestHistoricalAndIterationTwoBackwardCompatibility:
    """Section 25: the historical 102-slot and completed Iteration-2 24-slot
    resolutions must remain exactly as they were before this phase."""

    def test_all_102_historical_slots_still_resolve_and_verify(self):
        sequence = lib.load_global_sequence()
        assert len(sequence) == 102
        for entry in sequence:
            slot = lib.resolve_planned_slot(entry["campaign_sequence_index"], sequence=sequence)
            lib.verify_schedule_hash(slot)

    def test_all_24_iteration2_slots_still_resolve_to_frozen_design(self):
        sequence = i2.load_verified_i2_sequence()
        assert len(sequence) == 24
        for entry in sequence:
            slot = lib.resolve_planned_slot(entry["campaign_sequence_index"], sequence=sequence)
            assert slot["planned_slot_id"] == entry["planned_slot_id"]


class TestIterationTwoBIsolation:
    """Section 17/25: the Iteration-2B remediation context must be
    structurally isolated from BOTH the historical and Iteration-2
    contexts -- never able to resolve to the same paths."""

    def test_i2b_persistent_root_differs_from_historical_and_i2(self):
        assert i2b.I2B_PERSISTENT_ROOT != harness.CALIBRATION_ROOT
        assert i2b.I2B_PERSISTENT_ROOT != i2.I2_PERSISTENT_ROOT

    def test_i2b_ledger_differs_from_historical_and_i2(self):
        assert i2b.I2B_LEDGER_PATH != harness.LEDGER_PATH
        assert i2b.I2B_LEDGER_PATH != i2.I2_LEDGER_PATH

    def test_i2b_sequence_path_differs_from_historical_and_i2(self):
        assert i2b.I2B_SEQUENCE_PATH != lib.GLOBAL_SEQUENCE_PATH
        assert i2b.I2B_SEQUENCE_PATH != i2.I2_SEQUENCE_PATH

    def test_i2b_schedule_registry_differs_from_historical_and_i2(self):
        assert i2b.I2B_SCHEDULE_REGISTRY_PATH != lib.SCHEDULE_REGISTRY_PATH
        assert i2b.I2B_SCHEDULE_REGISTRY_PATH != i2.I2_SCHEDULE_REGISTRY_PATH

    def test_i2b_root_is_not_a_subpath_trick_of_historical_or_i2_root(self):
        assert harness.CALIBRATION_ROOT.resolve() not in i2b.I2B_PERSISTENT_ROOT.resolve().parents
        assert i2.I2_PERSISTENT_ROOT.resolve() not in i2b.I2B_PERSISTENT_ROOT.resolve().parents
        assert i2b.I2B_PERSISTENT_ROOT.resolve() != harness.CALIBRATION_ROOT.resolve()
        assert i2b.I2B_PERSISTENT_ROOT.resolve() != i2.I2_PERSISTENT_ROOT.resolve()


class TestIterationTwoBFailClosed:
    """Section 20/25: the Iteration-2B runner must refuse to proceed, never
    best-effort-continue, on any hash mismatch or out-of-range index."""

    def test_out_of_range_index_rejected(self):
        with pytest.raises(SystemExit):
            i2b.main(["--remediation-sequence-index", "0", "--dry-run"])
        with pytest.raises(SystemExit):
            i2b.main(["--remediation-sequence-index", "4", "--dry-run"])

    def test_design_yaml_hash_mismatch_fails_closed(self, monkeypatch):
        monkeypatch.setattr(i2b, "EXPECTED_PHASE16J1_DESIGN_YAML_SHA256", "0" * 64)
        with pytest.raises(RuntimeError, match="fail-closed"):
            i2b.load_verified_i2b_sequence()

    def test_sequence_projection_hash_mismatch_fails_closed(self, monkeypatch):
        monkeypatch.setattr(i2b, "EXPECTED_I2B_SEQUENCE_PROJECTION_SHA256", "0" * 64)
        with pytest.raises(RuntimeError, match="fail-closed"):
            i2b.load_verified_i2b_sequence()

    def test_missing_sequence_projection_fails_closed(self, monkeypatch, tmp_path):
        monkeypatch.setattr(i2b, "I2B_SEQUENCE_PATH", tmp_path / "does_not_exist.json")
        with pytest.raises(RuntimeError, match="fail-closed"):
            i2b.load_verified_i2b_sequence()

    def test_missing_schedule_registry_fails_closed(self, monkeypatch, tmp_path):
        monkeypatch.setattr(i2b, "I2B_SCHEDULE_REGISTRY_PATH", tmp_path / "does_not_exist.json")
        with pytest.raises(RuntimeError, match="fail-closed"):
            i2b.load_i2b_schedule_registry()

    def test_schedule_hash_mismatch_within_i2b_registry_fails_closed(self):
        real_sequence = i2b.load_verified_i2b_sequence()
        real_registry = i2b.load_i2b_schedule_registry()
        slot = lib.resolve_planned_slot(1, sequence=real_sequence)
        tampered_registry = json.loads(json.dumps(real_registry))
        tampered_registry[slot["cell_or_transition_id"]]["schedule_sha256"] = "0" * 64
        with pytest.raises(RuntimeError, match="mismatch"):
            lib.verify_schedule_hash(slot, registry=tampered_registry)


class TestIterationTwoBResolutionAndDryRun:
    """Section 24: all 3 Iteration-2B slots resolve exactly to the frozen
    Phase16J.1 remediation design and dry-run cleanly, without mutating the
    remediation ledger."""

    def test_i2b_sequence_has_exactly_3_slots(self):
        sequence = i2b.load_verified_i2b_sequence()
        assert len(sequence) == 3
        assert sorted(e["remediation_sequence_index"] for e in sequence) == [1, 2, 3]

    def test_all_3_slots_resolve_to_r7_rps24_5(self):
        sequence = i2b.load_verified_i2b_sequence()
        for entry in sequence:
            slot = lib.resolve_planned_slot(entry["campaign_sequence_index"], sequence=sequence)
            assert slot["replicas"] == 7
            assert slot["offered_rps"] == 24.5
            assert slot["cell_or_transition_id"] == "i2b_r7_mid"

    def test_i2b_slot_never_classified_as_a_transition_slot(self):
        sequence = i2b.load_verified_i2b_sequence()
        for entry in sequence:
            slot = lib.resolve_planned_slot(entry["campaign_sequence_index"], sequence=sequence)
            assert not lib.is_replica_transition_slot(slot)
            assert not lib.is_workload_transition_slot(slot)

    def test_dry_run_reports_isolated_artifact_root_and_correct_coordinates(self, monkeypatch):
        _patch_transport_discovery(monkeypatch)
        import io
        import contextlib

        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            rc = i2b.main(["--remediation-sequence-index", "1", "--dry-run"])
        assert rc == 0
        report = json.loads(buf.getvalue())
        assert report["artifact_destination_root"] == str(i2b.I2B_PERSISTENT_ROOT)
        assert report["artifact_destination_root"] != str(harness.CALIBRATION_ROOT)
        assert report["artifact_destination_root"] != str(i2.I2_PERSISTENT_ROOT)
        assert report["computed_schedule_sha256"] == report["expected_schedule_sha256"]

    def test_dry_run_does_not_mutate_remediation_ledger(self, monkeypatch):
        """Phase16J.2.1: the correct, lifecycle-independent invariant is that
        a dry-run never mutates the remediation ledger, whatever campaign
        state it happens to be in -- not that any one specific slot is
        NOT_ATTEMPTED (that was only ever true before Phase16J.2's live
        campaign legitimately populated the ledger). Byte-for-byte equality
        is the strictest, lifecycle-independent way to prove no mutation
        occurred."""
        _patch_transport_discovery(monkeypatch)
        import io
        import contextlib

        before_bytes = i2b.I2B_LEDGER_PATH.read_bytes()
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            rc = i2b.main(["--remediation-sequence-index", "2", "--dry-run"])
        after_bytes = i2b.I2B_LEDGER_PATH.read_bytes()

        assert rc == 0
        report = json.loads(buf.getvalue())
        assert report["planned_slot_id"] == "i2b_r7_mid_repeat2"
        assert report["replicas"] == 7
        assert report["offered_rps"] == 24.5
        assert after_bytes == before_bytes, "dry-run must never mutate the remediation ledger, regardless of campaign lifecycle state"


class TestIterationTwoBNoScientificOverride:
    """Section 20/29: none of the three CLIs provide an operator mechanism
    to alter a frozen slot's scientific parameters."""

    def test_i2b_cli_rejects_unknown_scientific_flags(self):
        parser = i2b.build_arg_parser()
        for flag in ("--replicas", "--offered-rps", "--schedule", "--duration", "--decision-timestamps"):
            with pytest.raises(SystemExit):
                parser.parse_args(["--remediation-sequence-index", "1", flag, "5"])

    def test_i2b_cli_only_exposes_execution_identifiers(self):
        parser = i2b.build_arg_parser()
        opts = {a.option_strings[0] for a in parser._actions if a.option_strings}
        assert opts == {"-h", "--remediation-sequence-index", "--attempt-number", "--session-id", "--dry-run"}

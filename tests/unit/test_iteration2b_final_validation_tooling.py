class TestCommonCvMaskAndLeakage:
    def test_expanded_common_cv_mask_size(self):
        rows = list(csv.DictReader(open(TASK_OUT / "phase_16k_expanded_common_cv_mask.csv")))
        assert len(rows) == 72  # 24 contributing cells x 3 folds

    def test_no_heldout_repeat_leakage_in_cv_predictions(self):
        """For every recorded CV prediction, the observed value must come
        from the held-out fold's OWN rows, never from training-fold rows --
        proven by re-deriving each instance's observed mean independently
        from the raw dataset and comparing to the recorded value."""
        dataset_rows = list(csv.DictReader(open(TASK_OUT / "phase_16k_iteration2b_model_fitting_dataset.csv")))
        by_cell_repeat = {}
        for r in dataset_rows:
            by_cell_repeat.setdefault((r["cell_id"], r["repeat_number"]), []).append(float(r["request_rate_rps"]))

        cv_rows = list(csv.DictReader(open(TASK_OUT / "phase_16e_style_cv_predictions_16k.csv")))
        checked = 0
        for r in cv_rows:
            if r["target"] != "request_rate_rps":
                continue
            vals = by_cell_repeat.get((r["cell_id"], r["fold"]))
            if not vals:
                continue
            expected_mean = sum(vals) / len(vals)
            assert abs(expected_mean - float(r["observed_cell_mean"])) < 1e-6
            checked += 1
        assert checked > 0



class TestIterationTwoBFinalValidationFailClosed:
    def test_out_of_range_index_rejected(self):
        with pytest.raises(SystemExit):
            i2bval.main(["--validation-sequence-index", "0", "--dry-run"])
        with pytest.raises(SystemExit):
            i2bval.main(["--validation-sequence-index", "33", "--dry-run"])

    def test_matrix_hash_mismatch_fails_closed(self, monkeypatch):
        monkeypatch.setattr(i2bval, "EXPECTED_MATRIX_SHA256", "0" * 64)
        with pytest.raises(RuntimeError, match="fail-closed"):
            i2bval.load_verified_i2bval_sequence()

    def test_sequence_projection_hash_mismatch_fails_closed(self, monkeypatch):
        monkeypatch.setattr(i2bval, "EXPECTED_SEQUENCE_PROJECTION_SHA256", "0" * 64)
        with pytest.raises(RuntimeError, match="fail-closed"):
            i2bval.load_verified_i2bval_sequence()

    def test_missing_schedule_registry_fails_closed(self, monkeypatch, tmp_path):
        monkeypatch.setattr(i2bval, "I2BVAL_SCHEDULE_REGISTRY_PATH", tmp_path / "does_not_exist.json")
        with pytest.raises(RuntimeError, match="fail-closed"):
            i2bval.load_i2bval_schedule_registry()

    def test_schedule_hash_mismatch_fails_closed(self):
        real_sequence = i2bval.load_verified_i2bval_sequence()
        real_registry = i2bval.load_i2bval_schedule_registry()
        slot = lib.resolve_planned_slot(1, sequence=real_sequence)
        tampered_registry = json.loads(json.dumps(real_registry))
        tampered_registry[slot["cell_or_transition_id"]]["schedule_sha256"] = "0" * 64
        with pytest.raises(RuntimeError, match="mismatch"):
            lib.verify_schedule_hash(slot, registry=tampered_registry)


class TestIterationTwoBFinalValidationDryRun:
    def test_dry_run_resolves_correct_coordinates(self, monkeypatch):
        _patch_transport_discovery(monkeypatch)
        import io
        import contextlib

        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            rc = i2bval.main(["--validation-sequence-index", "22", "--dry-run"])
        assert rc == 0
        report = json.loads(buf.getvalue())
        assert report["replicas"] == 7
        assert report["offered_rps"] == 17.5
        assert report["artifact_destination_root"] == str(i2bval.I2BVAL_PERSISTENT_ROOT)

    def test_dry_run_does_not_mutate_ledger(self, monkeypatch):
        _patch_transport_discovery(monkeypatch)
        before = i2bval.I2BVAL_LEDGER_PATH.read_bytes()
        i2bval.main(["--validation-sequence-index", "1", "--dry-run"])
        after = i2bval.I2BVAL_LEDGER_PATH.read_bytes()
        assert before == after


class TestIterationTwoBFinalValidationNoScientificOverride:
    def test_cli_rejects_unknown_scientific_flags(self):
        parser = i2bval.build_arg_parser()

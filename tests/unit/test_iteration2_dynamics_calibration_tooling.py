"""tests/unit/test_iteration2_dynamics_calibration_tooling.py

Phase 16I.1: backward-compatibility, isolation, and fail-closed tests for the
Iteration-2 dynamics-calibration execution tooling extension. These tests
prove that:

  1. The historical `scripts/run_dynamics_calibration_slot.py` CLI/behavior
     is byte-for-byte unchanged for a caller that supplies no new kwargs.
  2. The new Iteration-2 context (sequence, schedule registry, persistent
     root, ledger) is structurally isolated from the historical one and can
     never resolve to the historical paths.
  3. The Iteration-2 runner fails closed (raises, never proceeds) on any
     hash mismatch or out-of-range index.
  4. Neither CLI exposes an operator-facing override of any scientific
     parameter (replicas, offered_rps, schedule, duration, decision
     timestamps).

No traffic is generated by any test in this file; all live discovery calls
made by `--dry-run` are monkeypatched out exactly as the existing historical
dry-run tests already do.
"""
import json

import pytest

import scripts.dynamics_calibration_lib as lib
import scripts.run_dynamics_calibration_slot as harness
import scripts.run_iteration2_dynamics_calibration_slot as i2


def _patch_transport_discovery(monkeypatch):
    monkeypatch.setattr(harness, "resolve_minikube_docker_network", lambda: "minikube")
    monkeypatch.setattr(harness, "resolve_minikube_node_ip", lambda: "192.168.49.2")
    monkeypatch.setattr(harness, "resolve_loadtest_nodeport", lambda: 31891)
    monkeypatch.setattr(
        harness, "resolve_relay_image_identity",
        lambda: {"image": "alpine/socat", "image_id": None, "repo_digest": None},
    )


class TestHistoricalBackwardCompatibility:
    """Section 16/17: the historical execution context, invoked with no new
    kwargs, must resolve exactly as it did before this phase's changes."""

    def test_main_default_kwargs_match_historical_constants(self):
        import inspect

        sig = inspect.signature(harness.main)
        assert sig.parameters["calibration_root"].default == lib.CALIBRATION_ROOT
        assert sig.parameters["ledger_path"].default == lib.LEDGER_PATH
        assert sig.parameters["sequence_override"].default is None
        assert sig.parameters["schedule_registry_override"].default is None

    def test_all_102_historical_slots_resolve_and_verify(self):
        sequence = lib.load_global_sequence()
        assert len(sequence) == 102
        for entry in sequence:
            slot = lib.resolve_planned_slot(entry["campaign_sequence_index"], sequence=sequence)
            for key in ("planned_slot_id", "replicas", "offered_rps", "repeat_number", "run_kind"):
                if key in entry:
                    assert slot.get(key) == entry.get(key)
            # every historical schedule hash must still verify against the
            # UNCHANGED historical registry (default, no override supplied)
            lib.verify_schedule_hash(slot)

    def test_historical_dry_run_unchanged_after_refactor(self, monkeypatch, tmp_path):
        _patch_transport_discovery(monkeypatch)
        rc = harness.main(["--campaign-sequence-index", "1", "--dry-run"], ledger_path=tmp_path / "campaign_ledger.json")
        assert rc == 0

    def test_historical_cli_has_no_new_flags(self):
        parser = harness.build_arg_parser()
        opts = {a.option_strings[0] for a in parser._actions if a.option_strings}
        assert opts == {"-h", "--campaign-sequence-index", "--attempt-number", "--session-id", "--dry-run"}


class TestIterationTwoIsolation:
    """Section 6/19: the Iteration-2 campaign context must be structurally
    isolated from the historical one -- never able to resolve to the same
    paths."""

    def test_i2_persistent_root_differs_from_historical(self):
        assert i2.I2_PERSISTENT_ROOT != harness.CALIBRATION_ROOT
        assert str(i2.I2_PERSISTENT_ROOT) != str(harness.CALIBRATION_ROOT)

    def test_i2_ledger_differs_from_historical(self):
        assert i2.I2_LEDGER_PATH != harness.LEDGER_PATH

    def test_i2_sequence_path_differs_from_historical(self):
        assert i2.I2_SEQUENCE_PATH != lib.GLOBAL_SEQUENCE_PATH

    def test_i2_schedule_registry_differs_from_historical(self):
        assert i2.I2_SCHEDULE_REGISTRY_PATH != lib.SCHEDULE_REGISTRY_PATH

    def test_i2_root_is_not_a_subpath_trick_of_historical_root(self):
        # guards against e.g. persistent-data/dynamics_calibration/../dynamics_calibration_iteration2
        # resolving back into the historical tree via symlink/relative tricks
        assert harness.CALIBRATION_ROOT.resolve() not in i2.I2_PERSISTENT_ROOT.resolve().parents
        assert i2.I2_PERSISTENT_ROOT.resolve() != harness.CALIBRATION_ROOT.resolve()


class TestIterationTwoFailClosed:
    """Section 20: the Iteration-2 runner must refuse to proceed, never
    best-effort-continue, on any hash mismatch or out-of-range index."""

    def test_out_of_range_index_rejected(self):
        with pytest.raises(SystemExit):
            i2.main(["--iteration2-sequence-index", "0", "--dry-run"])
        with pytest.raises(SystemExit):
            i2.main(["--iteration2-sequence-index", "25", "--dry-run"])

    def test_development_sequence_hash_mismatch_fails_closed(self, monkeypatch):
        monkeypatch.setattr(i2, "EXPECTED_PHASE16H_DEVELOPMENT_SEQUENCE_SHA256", "0" * 64)
        with pytest.raises(RuntimeError, match="fail-closed"):
            i2.load_verified_i2_sequence()

    def test_sequence_projection_hash_mismatch_fails_closed(self, monkeypatch):
        monkeypatch.setattr(i2, "EXPECTED_I2_SEQUENCE_PROJECTION_SHA256", "0" * 64)
        with pytest.raises(RuntimeError, match="fail-closed"):
            i2.load_verified_i2_sequence()

    def test_missing_sequence_projection_fails_closed(self, monkeypatch, tmp_path):
        monkeypatch.setattr(i2, "I2_SEQUENCE_PATH", tmp_path / "does_not_exist.json")
        with pytest.raises(RuntimeError, match="fail-closed"):
            i2.load_verified_i2_sequence()

    def test_missing_schedule_registry_fails_closed(self, monkeypatch, tmp_path):
        monkeypatch.setattr(i2, "I2_SCHEDULE_REGISTRY_PATH", tmp_path / "does_not_exist.json")
        with pytest.raises(RuntimeError, match="fail-closed"):
            i2.load_i2_schedule_registry()

    def test_schedule_hash_mismatch_within_i2_registry_fails_closed(self):
        real_sequence = i2.load_verified_i2_sequence()
        real_registry = i2.load_i2_schedule_registry()
        slot = lib.resolve_planned_slot(1, sequence=real_sequence)
        tampered_registry = json.loads(json.dumps(real_registry))
        tampered_registry[slot["cell_or_transition_id"]]["schedule_sha256"] = "0" * 64
        with pytest.raises(RuntimeError, match="mismatch"):
            lib.verify_schedule_hash(slot, registry=tampered_registry)


class TestIterationTwoResolutionAndDryRun:
    """Section 18/22/23: all 24 Iteration-2 slots resolve exactly to the
    frozen Phase16H design and dry-run cleanly."""

    def test_i2_sequence_has_exactly_24_slots(self):
        sequence = i2.load_verified_i2_sequence()
        assert len(sequence) == 24
        assert sorted(e["campaign_sequence_index"] for e in sequence) == list(range(1, 25))

    def test_i2d_001_resolves_to_frozen_phase16h_coordinate(self):
        sequence = i2.load_verified_i2_sequence()
        slot = lib.resolve_planned_slot(1, sequence=sequence)
        assert slot["planned_slot_id"] == "i2dev_r5_L2_repeat2"
        assert slot["replicas"] == 5
        assert slot["offered_rps"] == 25.0
        assert slot["repeat_number"] == 2
        assert slot["run_kind"] == "iteration2_development_fitting"

    def test_i2_slot_never_classified_as_a_transition_slot(self):
        sequence = i2.load_verified_i2_sequence()
        for entry in sequence:
            slot = lib.resolve_planned_slot(entry["campaign_sequence_index"], sequence=sequence)
            assert not lib.is_replica_transition_slot(slot)
            assert not lib.is_workload_transition_slot(slot)

    def test_i2d_001_dry_run_reports_isolated_artifact_root(self, monkeypatch):
        _patch_transport_discovery(monkeypatch)
        import io
        import contextlib

        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            rc = i2.main(["--iteration2-sequence-index", "1", "--dry-run"])
        assert rc == 0
        report = json.loads(buf.getvalue())
        assert report["artifact_destination_root"] == str(i2.I2_PERSISTENT_ROOT)
        assert report["artifact_destination_root"] != str(harness.CALIBRATION_ROOT)
        assert report["computed_schedule_sha256"] == report["expected_schedule_sha256"]


class TestIterationTwoNoScientificOverride:
    """Section 8/21: neither CLI provides an operator mechanism to alter a
    frozen slot's scientific parameters."""

    def test_historical_cli_rejects_unknown_scientific_flags(self):
        parser = harness.build_arg_parser()
        for flag in ("--replicas", "--offered-rps", "--schedule", "--duration", "--decision-timestamps"):
            with pytest.raises(SystemExit):
                parser.parse_args(["--campaign-sequence-index", "1", flag, "5"])

    def test_i2_cli_rejects_unknown_scientific_flags(self):
        parser = i2.build_arg_parser()
        for flag in ("--replicas", "--offered-rps", "--schedule", "--duration", "--decision-timestamps"):
            with pytest.raises(SystemExit):
                parser.parse_args(["--iteration2-sequence-index", "1", flag, "5"])

    def test_i2_cli_only_exposes_execution_identifiers(self):
        parser = i2.build_arg_parser()
        opts = {a.option_strings[0] for a in parser._actions if a.option_strings}
        assert opts == {"-h", "--iteration2-sequence-index", "--attempt-number", "--session-id", "--dry-run"}
